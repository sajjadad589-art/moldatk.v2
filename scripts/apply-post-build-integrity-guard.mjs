import fs from 'node:fs';

const read = p => fs.readFileSync(p, 'utf8');
const write = (p, s) => fs.writeFileSync(p, s, 'utf8');
const must = (ok, msg) => { if (!ok) throw new Error(`Post-build integrity guard: ${msg}`); };

// Build-time patchers can add a call to extinguishDeletedTariffLiabilities while an
// older import from the same module already exists. Ensure the helper is imported
// without changing any tariff/accounting behavior.
{
  const p = 'src/App.tsx';
  let s = read(p);
  const modulePath = "'./utils/monthlyTariffDeletion'";
  const importRe = /import\s*\{([^}]*)\}\s*from\s*'\.\/utils\/monthlyTariffDeletion';/m;
  const match = s.match(importRe);
  must(match, 'monthlyTariffDeletion import missing');
  if (!match[1].split(',').map(x => x.trim()).includes('extinguishDeletedTariffLiabilities')) {
    const names = match[1].split(',').map(x => x.trim()).filter(Boolean);
    names.push('extinguishDeletedTariffLiabilities');
    s = s.replace(importRe, `import { ${names.join(', ')} } from ${modulePath};`);
  }
  write(p, s);
}

// Runtime patchers persist this compatibility snapshot on invoices. Keep it typed so
// the final TypeScript pass matches the runtime shape generated by the build chain.
{
  const p = 'src/types.ts';
  let s = read(p);
  if (!s.includes('remainingAfterPayment?: number;')) {
    const anchor = '  remainingAmount?: number;';
    must(s.includes(anchor), 'SubscriberInvoice remainingAmount field missing');
    s = s.replace(anchor, `${anchor}\n  remainingAfterPayment?: number;`);
  }
  write(p, s);
}

// Final visual invariant for the desktop dashboard. This does not alter values or
// accounting; it only guarantees one visible three-card finance row after all patchers.
{
  const p = 'src/components/DashboardView.tsx';
  const s = read(p);
  const rowCount = (s.match(/data-ampere-discount-dashboard-desktop-v1/g) || []).length;
  const debtCardCount = (s.match(/ديون الشهر السابق/g) || []).length;
  must(rowCount === 1, `expected one desktop finance row, found ${rowCount}`);
  must(debtCardCount === 1, `expected one previous-debt card, found ${debtCardCount}`);
}

console.log('Post-build integrity guard passed: finance row is single and generated financial types/imports are consistent.');
